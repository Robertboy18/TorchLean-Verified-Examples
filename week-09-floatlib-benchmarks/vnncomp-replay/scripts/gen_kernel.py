"""Write the Lean files in which Lean's kernel replays counterexamples of a family of small
fully connected networks (ACAS Xu), one file per network.

    python3 -I scripts/gen_kernel.py FAMILY WORK_DIR REPLAY_TSV OUT_DIR [--ids FILE] [--chunk N] [NET...]

`--ids FILE` keeps only the case ids listed in FILE (one per line); `--chunk N` writes at most N
cases per Lean file (`K_NET_cJ.lean`), so that several files of one network can be checked at once.

For every point of REPLAY_TSV (the reported point of a counterexample file and, where it lies
outside the box, the point moved into the box) the file states, as theorems proved by
`float_decide`:

    pK_lJ    : one layer applied to the literal words of its input gives the literal words of
               its output (the intermediate words are computed here with numpy and are only
               hints: the kernel recomputes every operation);
    pK_eval  : the network applied to the input words gives the output words;
    pK_in, pK_out, pK_full : the input part, the output part and the whole VNNLIB property hold,
               or do not hold, at these words, on exact rationals.

`OUT_DIR/manifest.tsv` maps every case id to its theorems and the verdicts the compiled replay
gave, so that a theorem the kernel rejects is a disagreement between the two.
"""
from __future__ import annotations

import csv
import sys
from fractions import Fraction
from pathlib import Path

import numpy as np

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import common  # noqa: E402
import crosscheck  # noqa: E402

PRELUDE = '''import FloatLib

/-!
Generated by `scripts/gen_kernel.py`. Counterexamples of neural-network verifiers,
replayed in Lean's kernel on FloatLib's `Binary32`.

A binary32 number is handled as its 32-bit word, a natural number. `net` maps the words of an
input to the words of the output: every layer decodes its words (`f32`), computes with FloatLib's
`Binary32` operations `*`, `+`, `-` and `<` (round to nearest, ties to even) in the reference
order (each dot product from `+0`, left to right, one multiplication and one addition per term,
then the bias), and encodes the result (`bits`). The property is read on exact rationals: `val`
is the rational that a word denotes, and a decimal constant of the property is that fraction.
-/

open FloatLib.Floats

set_option maxRecDepth 1000000
set_option maxHeartbeats 4000000

namespace VnnKernel

/-- The binary32 value of a word. -/
def f32 (n : Nat) : Binary32 := ExecFloat.Binary.ofNatBits n

/-- The word of a binary32 value. -/
def bits (v : Binary32) : Nat := ExecFloat.Binary.toNatBits v

/-- `(x_1 * w_1 + ... + x_n * w_n) + b`, accumulated from `+0` left to right. -/
def neuron (row : List Nat) (b : Nat) (x : List Nat) : Binary32 :=
  (List.zip x row).foldl (fun s p => s + f32 p.1 * f32 p.2) 0 + f32 b

/-- ONNX `Relu`. -/
def relu (v : Binary32) : Binary32 := if v < 0 then 0 else v

/-- A fully connected layer: ONNX `MatMul` followed by `Add`. -/
def affine (w : List (List Nat)) (b : List Nat) (x : List Nat) : List Nat :=
  List.zipWith (fun row bias => bits (neuron row bias x)) w b

/-- A fully connected layer followed by `Relu`. -/
def affineRelu (w : List (List Nat)) (b : List Nat) (x : List Nat) : List Nat :=
  List.zipWith (fun row bias => bits (relu (neuron row bias x))) w b

/-- ONNX `Sub` of a constant. -/
def subConst (c x : List Nat) : List Nat :=
  List.zipWith (fun xi ci => bits (f32 xi - f32 ci)) x c

/-- The exact rational that the `i`-th word of `v` denotes; `none` for an infinity or a NaN. -/
def val (v : List Nat) (i : Nat) : Option ℚ :=
  (v[i]?).bind fun n => ExecFloat.Binary.toRat? (f32 n)

/-- `a ≤ b` on values that both exist. -/
def oleb : Option ℚ → Option ℚ → Bool
  | some p, some q => decide (p ≤ q)
  | _, _ => false

end VnnKernel
'''


def words_list(words) -> str:
    return '[' + ', '.join(f'0x{int(w):08x}' for w in words) + ']'


def rational(text: str) -> str:
    q = Fraction(text)
    if q.denominator == 1:
        return f'({q.numerator} : ℚ)'
    return f'({q.numerator} / {q.denominator} : ℚ)'


def term(t, xname: str, yname: str) -> str:
    if t[0] == 'X':
        return f'val {xname} {t[1]}'
    if t[0] == 'Y':
        return f'val {yname} {t[1]}'
    return f'some {rational(t[1])}'


def is_input_atom(atom) -> bool:
    return all(t[0] != 'Y' for t in atom[1:])


def formula_lean(formula, part: str) -> str:
    """part: 'full', 'in' (output atoms are True) or 'out' (input atoms are True)."""
    head = formula[0]
    if head in ('and', 'or'):
        children = [formula_lean(child, part) for child in formula[1]]
        if head == 'and':
            children = [c for c in children if c != 'True']
            if not children:
                return 'True'
            return '(' + ' ∧ '.join(children) + ')'
        if any(c == 'True' for c in children):
            return 'True'
        return '(' + ' ∨ '.join(children) + ')'
    a, b = (formula[1], formula[2]) if head == 'le' else (formula[2], formula[1])
    if part == 'in' and not is_input_atom(formula):
        return 'True'
    if part == 'out' and is_input_atom(formula):
        return 'True'
    return f'oleb ({term(a, "x", "y")}) ({term(b, "x", "y")}) = true'


def trace(ops, x: np.ndarray):
    """The activations after every group of operations: sub, dense(+relu)."""
    groups = []
    index = 0
    while index < len(ops):
        op = ops[index]
        if op[0] == 'sub':
            x = crosscheck.evaluate([op], x)
            groups.append(('sub', op, x))
            index += 1
        elif op[0] == 'dense' and op[2] is not None:
            if index + 1 < len(ops) and ops[index + 1][0] == 'relu':
                x = crosscheck.evaluate([op, ops[index + 1]], x)
                groups.append(('affineRelu', op, x))
                index += 2
            else:
                x = crosscheck.evaluate([op], x)
                groups.append(('affine', op, x))
                index += 1
        else:
            raise ValueError(f'layer {op[0]} is not translated for the kernel')
    return groups


def to_words(array: np.ndarray):
    return [int(w) for w in np.ascontiguousarray(array, dtype=np.float32).view(np.uint32)]


def parse_spec(tokens, position=0):
    """The formula of a `spec` line of a cases file, in the form `common.parse_vnnlib` returns."""
    head = tokens[position]
    if head in ('and', 'or'):
        count = int(tokens[position + 1])
        position += 2
        children = []
        for _ in range(count):
            child, position = parse_spec(tokens, position)
            children.append(child)
        return (head, children), position

    def term(kind, text):
        return (kind, int(text)) if kind in ('X', 'Y') else (kind, text)
    return (head, term(tokens[position + 1], tokens[position + 2]),
            term(tokens[position + 3], tokens[position + 4])), position + 5


def main() -> None:
    family, work, replay_path, out_dir = sys.argv[1], Path(sys.argv[2]), sys.argv[3], Path(sys.argv[4])
    rest = sys.argv[5:]
    ids, chunk = None, 0
    while rest and rest[0] in ('--ids', '--chunk'):
        if rest[0] == '--ids':
            ids = {line.strip() for line in open(rest[1]) if line.strip()}
        else:
            chunk = int(rest[1])
        rest = rest[2:]
    only = set(rest)
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "VnnPrelude.lean").write_text(PRELUDE, encoding='utf-8')

    # the property of each case, as the cases file gives it to the compiled replay
    specs = {}
    with (work / 'cases' / f'{family}.cases').open() as stream:
        block = {}
        for line in stream:
            key, _, text = line.rstrip('\n').partition(' ')
            if key == 'end':
                if ids is None or block['case'] in ids:
                    specs[block['case']] = block['spec']
            else:
                block[key] = text
    rows = list(csv.DictReader(open(replay_path), delimiter='\t'))
    by_net: dict[str, list] = {}
    for row in rows:
        if row['status'] != 'ok' or (ids is not None and row['id'] not in ids):
            continue
        _, tool, net, prop, k = row['id'].split('|')
        if only and net not in only:
            continue
        by_net.setdefault(net, []).append((row, tool, prop, int(k)))

    manifest = []
    modules = []
    for net in sorted(by_net):
        cases = by_net[net]
        if chunk:
            for start in range(0, len(cases), chunk):
                modules.append((net, f'K_{net}_c{start // chunk}', cases[start:start + chunk]))
        else:
            modules.append((net, 'K_' + net, cases))
    for net, module, cases in modules:
        net_path = work / 'nets' / family / f'{net}.net'
        ops = crosscheck.load_net(str(net_path))
        # A property is a conjunction, and Lean finds its `Decidable` instance by instance synthesis,
        # whose default size limit (128) is reached at about 64 atoms: lift it for larger properties.
        atoms = max(len(list(common.formula_atoms(parse_spec(specs[row['id']].split())[0])))
                    for row, _, _, _ in cases)
        options = ['set_option maxRecDepth 1000000', 'set_option maxHeartbeats 4000000']
        if atoms > 60:
            options += ['set_option synthInstance.maxSize 100000', 'set_option synthInstance.maxHeartbeats 4000000']
        lines = ['import VnnPrelude', '', 'open FloatLib.Floats', ''] + options + ['',
                 f'namespace VnnKernel.{module[2:]}', '']
        # the network
        groups = trace(ops, np.zeros(ops[0][1].size if ops[0][0] == 'sub' else ops[0][1].shape[1], dtype=np.float32))
        expr = 'x'
        for index, (kind, op, _) in enumerate(groups):
            if kind == 'sub':
                lines.append(f'/-- The constant of the `Sub` node. -/')
                lines.append(f'def c{index} : List Nat := {words_list(to_words(op[1]))}')
                expr = f'subConst c{index} ({expr})'
            else:
                weight, bias = op[1], op[2]
                rows_text = ',\n  '.join(words_list(to_words(r)) for r in weight)
                lines.append(f'/-- Weights of layer {index}: one row per output, `[out][in]`. -/')
                lines.append(f'def w{index} : List (List Nat) := [\n  {rows_text}]')
                lines.append(f'/-- Bias of layer {index}. -/')
                lines.append(f'def b{index} : List Nat := {words_list(to_words(bias))}')
                expr = f'{kind} w{index} b{index} ({expr})'
            lines.append('')
        lines.append('/-- The network on binary32 words. -/')
        lines.append(f'def net (x : List Nat) : List Nat :=\n  {expr}')
        lines.append('')
        # the properties
        defined_props = set()
        points = {}       # x words -> point name
        verdicts = {}     # (point name, prop) -> theorem prefix
        axioms = []
        for row, tool, prop, k in cases:
            if prop not in defined_props:
                defined_props.add(prop)
                formula, _ = parse_spec(specs[row['id']].split())
                lines.append(f'/-- VNNLIB property `{prop}`: a counterexample makes it true. -/')
                lines.append(f'def {prop} (x y : List Nat) : Prop :=\n  {formula_lean(formula, "full")}')
                lines.append(f'/-- The input part of `{prop}`. -/')
                lines.append(f'def {prop}_in (x : List Nat) : Prop :=\n  {formula_lean(formula, "in")}')
                lines.append(f'/-- The output part of `{prop}`. -/')
                lines.append(f'def {prop}_out (y : List Nat) : Prop :=\n  {formula_lean(formula, "out")}')
                lines.append('')
            variants = [('reported', row['x_bits'], row['y_bits'], row['in_exact'], row['out32'], row['full'])]
            if row['moved'] != '0':
                variants.append(('projected', row['proj_x_bits'], row['proj_y_bits'], row['proj_in_exact'],
                                 row['proj_out32'], row['proj_full']))
            for which, x_bits, y_bits, v_in, v_out, v_full in variants:
                x_words = [int(t, 16) for t in x_bits.split(',')]
                y_words = [int(t, 16) for t in y_bits.split(',')]
                key = tuple(x_words)
                if key not in points:
                    name = f'p{len(points) + 1}'
                    points[key] = name
                    x = np.array(x_words, dtype=np.uint32).view(np.float32)
                    with np.errstate(all='ignore'):
                        steps = trace(ops, x)
                    current = x_words
                    lemma_names = []
                    lines.append(f'/-! Point `{name}`: first seen in `{row["id"]}` ({which}). -/')
                    for index, (kind, _, activation) in enumerate(steps):
                        nxt = to_words(activation)
                        call = f'subConst c{index}' if kind == 'sub' else f'{kind} w{index} b{index}'
                        unfold = '[subConst, f32, bits]' if kind == 'sub' else f'[{kind}, neuron, relu, f32, bits]'
                        if kind == 'affine':
                            unfold = '[affine, neuron, f32, bits]'
                        lines.append(f'theorem {name}_l{index} : {call} {words_list(current)} =\n'
                                     f'    {words_list(nxt)} := by\n  float_decide {unfold}')
                        lemma_names.append(f'{name}_l{index}')
                        current = nxt
                    if current != y_words:
                        raise SystemExit(f'numpy and the compiled replay disagree on {row["id"]} ({which})')
                    lines.append(f'/-- The network at point `{name}`, in binary32. -/')
                    lines.append(f'theorem {name}_eval : net {words_list(x_words)} =\n'
                                 f'    {words_list(y_words)} := by\n  rw [net, ' + ', '.join(lemma_names) + ']')
                    lines.append('')
                    axioms.append(f'{name}_eval')
                name = points[key]
                if (name, prop) not in verdicts:
                    prefix = f'{name}_{prop}'
                    verdicts[(name, prop)] = prefix
                    xl, yl = words_list(x_words), words_list(y_words)
                    neg_in = '' if v_in == '1' else '¬ '
                    neg_out = '' if v_out == '1' else '¬ '
                    neg_full = '' if v_full == '1' else '¬ '
                    lines.append(f'/-- Input part of `{prop}` at `{name}`. -/')
                    lines.append(f'theorem {prefix}_in : {neg_in}{prop}_in {xl} := by\n'
                                 f'  float_decide [{prop}_in, val, oleb, f32]')
                    lines.append(f'/-- Output part of `{prop}` at the binary32 output of `{name}`. -/')
                    lines.append(f'theorem {prefix}_out : {neg_out}{prop}_out (net {xl}) := by\n'
                                 f'  rw [{name}_eval]\n  float_decide [{prop}_out, val, oleb, f32]')
                    lines.append(f'/-- `{prop}` at `{name}`: the point is{"" if v_full == "1" else " not"} a counterexample. -/')
                    lines.append(f'theorem {prefix}_full : {neg_full}{prop} {xl} (net {xl}) := by\n'
                                 f'  rw [{name}_eval]\n  float_decide [{prop}, val, oleb, f32]')
                    lines.append('')
                    axioms += [f'{prefix}_in', f'{prefix}_out', f'{prefix}_full']
                manifest.append([row['id'], which, module, f'VnnKernel.{module[2:]}.{name}_eval',
                                 f'VnnKernel.{module[2:]}.{verdicts[(name, prop)]}', v_in, v_out, v_full])
        for name in axioms:
            lines.append(f'#print axioms {name}')
        lines.append('')
        lines.append(f'end VnnKernel.{module[2:]}')
        (out_dir / f'{module}.lean').write_text('\n'.join(lines) + '\n', encoding='utf-8')
        print(f'{module}: {len(points)} points, {len(verdicts)} verdict groups, {len(axioms)} theorems to audit')
    with (out_dir / 'manifest.tsv').open('w', newline='') as stream:
        writer = csv.writer(stream, delimiter='\t', lineterminator='\n')
        writer.writerow(['id', 'point', 'module', 'eval_theorem', 'verdict_prefix', 'in', 'out', 'full'])
        writer.writerows(manifest)


if __name__ == '__main__':
    main()
